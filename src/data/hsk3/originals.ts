// Original HSK 3 practice exams written for HSK Path, in the exact format of the official paper.
// Vocabulary kept within HSK levels 1–3. Listening is read by speech synthesis (each item can be played twice).
import type { H3Exam, H3Question, H3Group } from './types';

type L1 = [transcript: string, answer: string];
type TF = [transcript: string, statement: string, answer: '√' | '×'];
type MC = [transcript: string, options: [string, string, string], answer: 'A' | 'B' | 'C'];
type Q2 = [text: string, answer: string];
type RC = [passage: string, question: string, options: [string, string, string], answer: 'A' | 'B' | 'C'];
type OR = [words: string[], answer: string, alts?: string[]];
type CH = [pinyin: string, text: string, answer: string];

interface Spec {
  id: string;
  code: string;
  title: string;
  g1: Record<string, string>;
  g1Example: string;
  g2: Record<string, string>;
  l1: L1[];
  tf: TF[];
  mc: MC[];
  m1: Record<string, string>;
  m1Example: string;
  m1q: Q2[];
  m2: Record<string, string>;
  m2q: Q2[];
  b1: Record<string, string>;
  b1Example: string;
  b1q: Q2[];
  b2: Record<string, string>;
  b2Example: string;
  b2q: Q2[];
  rc: RC[];
  order: OR[];
  chars: CH[];
}

function build(s: Spec): H3Exam {
  const groups: H3Group[] = [
    { id: 'g1', range: [1, 5], kind: 'icon', options: s.g1, example: { letter: 'D', text: s.g1Example } },
    { id: 'g2', range: [6, 10], kind: 'icon', options: s.g2 },
    { id: 'm1', range: [41, 45], kind: 'text', options: s.m1, example: { letter: 'E', text: s.m1Example } },
    { id: 'm2', range: [46, 50], kind: 'text', options: s.m2 },
    { id: 'b1', range: [51, 55], kind: 'word', options: s.b1, example: { letter: 'E', text: s.b1Example } },
    { id: 'b2', range: [56, 60], kind: 'word', options: s.b2, example: { letter: 'D', text: s.b2Example } },
  ];
  const q: H3Question[] = [];
  let n = 1;
  s.l1.forEach(([t, a]) => { q.push({ n, type: 'l-img', group: n <= 5 ? 'g1' : 'g2', transcript: t, answer: a }); n++; });
  s.tf.forEach(([t, st, a]) => { q.push({ n, type: 'l-tf', statement: st, transcript: `${t}\n★ ${st}`, answer: a }); n++; });
  s.mc.forEach(([t, o, a]) => { q.push({ n, type: 'l-mc', options: o, transcript: t, answer: a }); n++; });
  s.m1q.forEach(([t, a]) => { q.push({ n, type: 'r-match', group: 'm1', text: t, answer: a }); n++; });
  s.m2q.forEach(([t, a]) => { q.push({ n, type: 'r-match', group: 'm2', text: t, answer: a }); n++; });
  s.b1q.forEach(([t, a]) => { q.push({ n, type: 'r-bank', group: 'b1', text: t, answer: a }); n++; });
  s.b2q.forEach(([t, a]) => { q.push({ n, type: 'r-bank', group: 'b2', text: t, answer: a }); n++; });
  s.rc.forEach(([p, qq, o, a]) => { q.push({ n, type: 'r-mc', passage: p, question: qq, options: o, answer: a }); n++; });
  s.order.forEach(([w, a, alts]) => { q.push({ n, type: 'w-order', words: w, answer: a, ...(alts ? { alts } : {}) }); n++; });
  s.chars.forEach(([py, t, a]) => { q.push({ n, type: 'w-char', pinyin: py, text: t, answer: a }); n++; });
  if (q.length !== 80) throw new Error(`${s.code}: ${q.length} questions`);
  return { id: s.id, code: s.code, title: s.title, source: 'original', isPro: true, groups, questions: q };
}

